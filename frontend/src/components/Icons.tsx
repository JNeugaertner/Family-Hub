interface IconProps {
  size?: number;
  className?: string;
  strokeWidth?: number;
}

const icon = (paths: string, viewBox = '0 0 24 24') =>
  function Icon({ size = 20, className = '', strokeWidth = 1.8 }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox={viewBox}
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        aria-hidden="true"
      >
        {paths.split('|').map((d, i) => (
          d.startsWith('circle:') ? (
            <circle key={i} {...Object.fromEntries(d.slice(7).split(',').map(p => p.split(':')))} />
          ) : d.startsWith('rect:') ? (
            <rect key={i} {...Object.fromEntries(d.slice(5).split(',').map(p => p.split(':')))} />
          ) : d.startsWith('line:') ? (
            <line key={i} {...Object.fromEntries(d.slice(5).split(',').map(p => p.split(':')))} />
          ) : (
            <path key={i} d={d} />
          )
        ))}
      </svg>
    );
  };

